/**
 * The federal rules for the tax year being prepared. Each tax year has its own parameter file (rules2025.ts,
 * rules2026.ts, ...) with the same exports; useTaxYear() switches every export of this module to that year.
 * ES module exports are live bindings, so code that imports from here sees the switch. computeReturn() calls
 * useTaxYear() with the return's year before it computes anything.
 *
 * Adding a year: copy the latest rulesYYYY.ts, update every amount from that year's Rev. Proc. and law
 * changes, add it to BY_YEAR and TAX_YEARS below.
 */
import * as Y2025 from './rules2025.ts'
import * as Y2026 from './rules2026.ts'

