'use strict'
const assert = require('assert')
const fs = require('fs')
const path = require('path')
const {compareCandidateToModel} = require('./compare-2025-candidate-to-model')
const model = fs.readFileSync(path.join(__dirname, '../research/2025-tax-table-RECONSTRUCTED.csv'), 'utf8')
const result = compareCandidateToModel(model, model)
assert.strictEqual(result.intervalsCompared, 2062)
assert.strictEqual(result.taxValuesCompared, 8248)
assert.strictEqual(result.differenceCount, 0)
assert.strictEqual(result.filingReady, false)
assert.strictEqual(result.independentlyVerifiedAgainstIRS, false)
const lines = model.trim().split(/\r?\n/)
const altered = lines.slice()
const target = 500
const cells = altered[target].split(',')
cells[2] = String(Number(cells[2]) + 1)
altered[target] = cells.join(',')
const changed = compareCandidateToModel(altered.join('\n') + '\n', model)
assert.strictEqual(changed.differenceCount, 1)
assert.strictEqual(changed.differences[0].filingStatus, 'single')
assert.throws(() => compareCandidateToModel('lower,upper,single\n0,5,0', model))
console.log('Stage 46 diagnostic comparison tests: 7 assertions passed')
